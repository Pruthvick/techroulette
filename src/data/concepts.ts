const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

export const concepts: Concept[] = Object.entries(bank).flatMap(([category, byLevel]) =>
  (Object.keys(byLevel) as Difficulty[]).flatMap((difficulty) =>
    byLevel[difficulty].map((name) => ({
      id: `${slug(category)}--${slug(name)}`,
      name,
      category,
      difficulty,
      interviewQuestion: `What is ${name}?`,
    })),
  ),
);

export const categories = Object.keys(bank);

export const difficulties: Difficulty[] = ["Beginner", "Intermediate", "Advanced"];

export function pickRandomConcept(
  opts: { category?: string | null; difficulty?: Difficulty | null; exclude?: string[] } = {},
): Concept | null {
  const { category, difficulty, exclude = [] } = opts;
  let pool = concepts.filter(
    (c) =>
      (!category || category === "All Topics" || c.category === category) &&
      (!difficulty || c.difficulty === difficulty),
  );
  if (pool.length === 0) return null;
  const fresh = pool.filter((c) => !exclude.includes(c.id));
  if (fresh.length > 0) pool = fresh;
  return pool[Math.floor(Math.random() * pool.length)] ?? null;
}
